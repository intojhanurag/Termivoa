import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = path.join(root, 'protocol/v1/types.schema.json');
const envelopeSchema = path.join(root, 'protocol/v1/envelope.schema.json');
const outputs = [
  [
    'go',
    path.join(root, 'internal/protocol/generated.go'),
    ['--package', 'protocol', '--just-types-and-package'],
  ],
  [
    'typescript',
    path.join(root, 'web/src/generated/protocol.ts'),
    ['--just-types', '--prefer-types', '--readonly'],
  ],
];

for (const [language, output, extra] of outputs) {
  mkdirSync(path.dirname(output), { recursive: true });
  const result = spawnSync(
    'pnpm',
    [
      'exec',
      'quicktype',
      '--src-lang',
      'schema',
      '--lang',
      language,
      '--src',
      schema,
      '--additional-schema',
      envelopeSchema,
      '--out',
      output,
      '--top-level',
      'ProtocolTypes',
      '--no-uuids',
      '--no-integer-strings',
      ...extra,
    ],
    { cwd: root, encoding: 'utf8', stdio: 'inherit' },
  );
  if (result.error !== undefined) {
    throw result.error;
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }

  const generated = readFileSync(output, 'utf8');
  const header = '// Code generated by scripts/generate-protocol.mjs; DO NOT EDIT.\n\n';
  writeFileSync(output, header + generated);
}
