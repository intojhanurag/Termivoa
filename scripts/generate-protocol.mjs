import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = path.join(root, 'protocol/v1/types.schema.json');
const envelopeSchema = path.join(root, 'protocol/v1/envelope.schema.json');
const ipcSchema = path.join(root, 'protocol/v1/ipc.schema.json');
const brokerRPCSchema = path.join(root, 'protocol/v1/broker-rpc.schema.json');
const httpAPISchema = path.join(root, 'protocol/v1/http-api.schema.json');
const gatewayRPCSchema = path.join(root, 'protocol/v1/gateway-rpc.schema.json');
const adminRPCSchema = path.join(root, 'protocol/v1/admin-rpc.schema.json');
const { revision, minRevision } = JSON.parse(readFileSync(path.join(root, 'protocol/v1/revision.json'), 'utf8'));
if (!Number.isInteger(revision) || !Number.isInteger(minRevision) || minRevision < 1 || minRevision > revision) {
  console.error('protocol/v1/revision.json needs integers 1 <= minRevision <= revision.');
  process.exit(1);
}
// Every $ref must resolve: quicktype skips some unreachable definitions, so a
// broken reference would otherwise pass generation silently (#134).
const schemaDir = path.join(root, 'protocol/v1');
const unresolved = [];
for (const file of ['types', 'envelope', 'ipc', 'broker-rpc', 'http-api', 'gateway-rpc', 'admin-rpc'].map((name) => `${name}.schema.json`)) {
  const text = readFileSync(path.join(schemaDir, file), 'utf8');
  for (const [, ref] of text.matchAll(/"\$ref"\s*:\s*"([^"]*)"/g)) {
    const [target, pointer = ''] = ref.split('#');
    let node = JSON.parse(readFileSync(path.join(schemaDir, target || file), 'utf8'));
    for (const key of pointer.split('/').slice(1)) node = node?.[key.replaceAll('~1', '/').replaceAll('~0', '~')];
    if (node === undefined) unresolved.push(`${file}: ${ref}`);
  }
}
if (unresolved.length > 0) {
  console.error(`Unresolved $ref in protocol/v1:\n  ${unresolved.join('\n  ')}`);
  process.exit(1);
}
// The revision is one integer, emitted into both languages from revision.json.
const revisionCode = {
  go: `
// ProtocolRevision is this build's additive protocol v1 revision and
// MinProtocolRevision the oldest peer revision it supports (protocol/v1/revision.json).
const (
	ProtocolRevision    = ${revision}
	MinProtocolRevision = ${minRevision}
)
`,
  typescript: `
/** This build's additive protocol v1 revision (protocol/v1/revision.json). */
export const PROTOCOL_REVISION = ${revision};
/** The oldest peer protocol revision this build supports. */
export const MIN_PROTOCOL_REVISION = ${minRevision};
`,
};
// Run quicktype's JS entry point with this Node binary. Spawning `pnpm` (a .cmd shim on
// Windows) needs a shell there, so going through node keeps it the same on every OS.
const quicktypeCLI = findQuicktypeCLI();

function findQuicktypeCLI() {
  const require = createRequire(import.meta.url);
  try {
    const quicktypePackage = require.resolve('quicktype/package.json');
    const { bin } = require(quicktypePackage);
    const entry = typeof bin === 'string' ? bin : bin?.quicktype;
    if (typeof entry !== 'string') {
      throw new Error('its package.json has no quicktype bin entry');
    }
    return path.join(path.dirname(quicktypePackage), entry);
  } catch (error) {
    console.error(`Cannot find the quicktype CLI (${error.message}). Run pnpm install --frozen-lockfile.`);
    process.exit(1);
  }
}
const outputs = [
  [
    'go',
    path.join(root, 'internal/protocol/generated.go'),
    ['--package', 'protocol', '--just-types-and-package'],
  ],
  [
    'typescript',
    path.join(root, 'web/src/generated/protocol.ts'),
    ['--just-types', '--prefer-types', '--readonly'],
  ],
];

for (const [language, output, extra] of outputs) {
  mkdirSync(path.dirname(output), { recursive: true });
  const result = spawnSync(
    process.execPath,
    [
      quicktypeCLI,
      '--src-lang',
      'schema',
      '--lang',
      language,
      '--src',
      schema,
      '--additional-schema',
      envelopeSchema,
      '--additional-schema',
      ipcSchema,
      '--additional-schema',
      brokerRPCSchema,
      '--additional-schema',
      httpAPISchema,
      '--additional-schema',
      gatewayRPCSchema,
      '--additional-schema',
      adminRPCSchema,
      '--out',
      output,
      '--top-level',
      'ProtocolTypes',
      '--no-uuids',
      '--no-integer-strings',
      ...extra,
    ],
    { cwd: root, encoding: 'utf8', stdio: 'inherit' },
  );
  if (result.error !== undefined) {
    throw result.error;
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }

  const generated = readFileSync(output, 'utf8');
  const header = '// Code generated by scripts/generate-protocol.mjs; DO NOT EDIT.\n\n';
  writeFileSync(output, header + generated + revisionCode[language]);

  if (language === 'go') {
    // quicktype output is not always gofmt-clean (e.g. long field comments break alignment).
    const fmt = spawnSync('gofmt', ['-w', output], { cwd: root, encoding: 'utf8', stdio: 'inherit' });
    if (fmt.error !== undefined) {
      console.error(`gofmt failed to run (${fmt.error.message}). Install Go and put gofmt on PATH.`);
      process.exit(1);
    }
    if (fmt.status !== 0) {
      process.exit(fmt.status ?? 1);
    }
  }
}
