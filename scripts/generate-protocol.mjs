import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = path.join(root, 'protocol/v1/types.schema.json');
const envelopeSchema = path.join(root, 'protocol/v1/envelope.schema.json');
const ipcSchema = path.join(root, 'protocol/v1/ipc.schema.json');
const brokerRPCSchema = path.join(root, 'protocol/v1/broker-rpc.schema.json');
const httpAPISchema = path.join(root, 'protocol/v1/http-api.schema.json');
const gatewayRPCSchema = path.join(root, 'protocol/v1/gateway-rpc.schema.json');
const adminRPCSchema = path.join(root, 'protocol/v1/admin-rpc.schema.json');
// Run quicktype's JS entry point with this Node binary. Spawning `pnpm` (a .cmd shim on
// Windows) needs a shell there, so going through node keeps it the same on every OS.
const require = createRequire(import.meta.url);
const quicktypePackage = require.resolve('quicktype/package.json');
const { bin } = require(quicktypePackage);
const quicktypeCLI = path.join(path.dirname(quicktypePackage), typeof bin === 'string' ? bin : bin.quicktype);
const outputs = [
  [
    'go',
    path.join(root, 'internal/protocol/generated.go'),
    ['--package', 'protocol', '--just-types-and-package'],
  ],
  [
    'typescript',
    path.join(root, 'web/src/generated/protocol.ts'),
    ['--just-types', '--prefer-types', '--readonly'],
  ],
];

for (const [language, output, extra] of outputs) {
  mkdirSync(path.dirname(output), { recursive: true });
  const result = spawnSync(
    process.execPath,
    [
      quicktypeCLI,
      '--src-lang',
      'schema',
      '--lang',
      language,
      '--src',
      schema,
      '--additional-schema',
      envelopeSchema,
      '--additional-schema',
      ipcSchema,
      '--additional-schema',
      brokerRPCSchema,
      '--additional-schema',
      httpAPISchema,
      '--additional-schema',
      gatewayRPCSchema,
      '--additional-schema',
      adminRPCSchema,
      '--out',
      output,
      '--top-level',
      'ProtocolTypes',
      '--no-uuids',
      '--no-integer-strings',
      ...extra,
    ],
    { cwd: root, encoding: 'utf8', stdio: 'inherit' },
  );
  if (result.error !== undefined) {
    throw result.error;
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }

  const generated = readFileSync(output, 'utf8');
  const header = '// Code generated by scripts/generate-protocol.mjs; DO NOT EDIT.\n\n';
  writeFileSync(output, header + generated);

  if (language === 'go') {
    // quicktype output is not always gofmt-clean (e.g. long field comments break alignment).
    const fmt = spawnSync('gofmt', ['-w', output], { cwd: root, encoding: 'utf8', stdio: 'inherit' });
    if (fmt.error !== undefined) {
      console.error(`gofmt failed to run (${fmt.error.message}). Install Go and put gofmt on PATH.`);
      process.exit(1);
    }
    if (fmt.status !== 0) {
      process.exit(fmt.status ?? 1);
    }
  }
}
